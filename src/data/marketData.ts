function generateChartHistory(basePrice: number, volatility: number = 0.015): Record<ChartTimeframe, PricePoint[]> {
  const timeframes: ChartTimeframe[] = ['1D', '5D', '1M', '6M', '1Y', 'ALL'];
  const result: Partial<Record<ChartTimeframe, PricePoint[]>> = {};

  timeframes.forEach((tf) => {
    let count = 28;
    if (tf === '1D') count = 32;
    else if (tf === '5D') count = 35;
    else if (tf === '1M') count = 30;
    else if (tf === '6M') count = 40;
    else if (tf === '1Y') count = 52;
    else if (tf === 'ALL') count = 60;

    let current = basePrice * (1 - volatility * (count / 5));
    const points: PricePoint[] = [];

    // Indicator calculation helpers
    let prevEma12 = current;
    let prevEma26 = current;
    let prevSignal = 0;
    let avgGain = volatility * basePrice * 0.5;
    let avgLoss = volatility * basePrice * 0.4;

    for (let i = 0; i < count; i++) {
      const delta = (Math.sin(i * 0.45) * 0.7 + (Math.random() - 0.47) * 1.6) * volatility * basePrice;
      const open = current;
      current = Math.max(0.1, current + delta);
      const close = current;
      const high = Math.max(open, close) + Math.random() * volatility * basePrice * 0.7;
      const low = Math.min(open, close) - Math.random() * volatility * basePrice * 0.7;
      const volume = Math.floor(Math.random() * 800000 + 200000);

      // RSI
      const change = close - open;
      if (change > 0) {
        avgGain = (avgGain * 13 + change) / 14;
        avgLoss = (avgLoss * 13) / 14;
      } else {
        avgGain = (avgGain * 13) / 14;
        avgLoss = (avgLoss * 13 + Math.abs(change)) / 14;
      }
      const rs = avgLoss === 0 ? 100 : avgGain / avgLoss;
      const rsi = Math.min(95, Math.max(10, 100 - 100 / (1 + rs)));

      // MACD
      const k12 = 2 / 13;
      const k26 = 2 / 27;
      prevEma12 = close * k12 + prevEma12 * (1 - k12);
      prevEma26 = close * k26 + prevEma26 * (1 - k26);
      const macd = prevEma12 - prevEma26;
      const k9 = 2 / 10;
      prevSignal = macd * k9 + prevSignal * (1 - k9);
      const macdHist = macd - prevSignal;

      // Bollinger Bands approximation
      const stdDev = volatility * basePrice * 1.5;
      const bbMiddle = close;
      const bbUpper = close + 2 * stdDev;
      const bbLower = Math.max(0, close - 2 * stdDev);

      let label = '';
      if (tf === '1D') {
        const hour = Math.floor(9 + (i * 7) / count);
        const min = Math.floor(((i * 7 * 60) / count) % 60);
        label = `${hour.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}`;
      } else if (tf === '5D') {
        const days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
        label = `${days[Math.floor((i / count) * 5)] || 'Fri'} ${Math.floor(i % 7)}h`;
      } else if (tf === '1M') {
        label = `Day ${i + 1}`;
      } else if (tf === '6M') {
        const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
        label = months[i % 12];
      } else if (tf === '1Y') {
        label = `Wk ${i + 1}`;
      } else {
        label = `${2019 + Math.floor((i / count) * 5)}`;
      }

      points.push({
        time: label,
        price: Number(close.toFixed(2)),
        open: Number(open.toFixed(2)),
        high: Number(high.toFixed(2)),
        low: Number(low.toFixed(2)),
        close: Number(close.toFixed(2)),
        volume,
        rsi: Number(rsi.toFixed(1)),
        macd: Number(macd.toFixed(2)),
        macdSignal: Number(prevSignal.toFixed(2)),
        macdHist: Number(macdHist.toFixed(2)),
        bbUpper: Number(bbUpper.toFixed(2)),
        bbLower: Number(bbLower.toFixed(2)),
        bbMiddle: Number(bbMiddle.toFixed(2)),
      });
    }
    result[tf] = points;
  });

  return result as Record<ChartTimeframe, PricePoint[]>;
}

